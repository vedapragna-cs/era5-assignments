"""EVIDENCE.md, generated from logs/ rather than written alongside it.

Every claim below is read out of a JSON artifact produced by the run that just finished. A
hand-written evidence document drifts from the run it describes on the first change nobody
remembers to propagate; this one cannot, because there is nowhere for it to store a claim
the artifacts do not contain.

Where a check has a pass/fail character the row is marked PASS or FAIL from the artifact's
own value, not from a hard-coded expectation. A FAIL row is left in the document.
"""

from __future__ import annotations

import json
import os
from typing import Any, Callable, Dict, List, Optional


def _load(logs: str, name: str) -> Optional[Dict[str, Any]]:
    path = os.path.join(logs, name)
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        return json.load(fh)


def _mark(ok: Optional[bool]) -> str:
    if ok is None:
        return "n/a "
    return "PASS" if ok else "FAIL"


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return "{:.4f}".format(v)
    if isinstance(v, dict):
        return ", ".join("{}={}".format(k, _fmt(x)) for k, x in list(v.items())[:6])
    if isinstance(v, list):
        return ", ".join(str(x) for x in v[:6])
    return str(v)


class _Doc:
    def __init__(self) -> None:
        self.lines: List[str] = []

    def h(self, level: int, text: str) -> None:
        self.lines.append("")
        self.lines.append("#" * level + " " + text)
        self.lines.append("")

    def p(self, text: str) -> None:
        self.lines.append(text)
        self.lines.append("")

    def table(self, headers: List[str], rows: List[List[Any]]) -> None:
        self.lines.append("| " + " | ".join(headers) + " |")
        self.lines.append("|" + "|".join(["---"] * len(headers)) + "|")
        for row in rows:
            self.lines.append("| " + " | ".join(_fmt(c) for c in row) + " |")
        self.lines.append("")

    def code(self, text: str) -> None:
        self.lines.append("```")
        self.lines.append(text)
        self.lines.append("```")
        self.lines.append("")

    def render(self) -> str:
        return "\n".join(self.lines).strip() + "\n"


def write_evidence(ledgers: str, root: str, bundle_root: Optional[str] = None) -> str:
    """The long-form companion to submission_artifacts/evidence.md.

    evidence.md is the graded table: one row per requirement, terse. This is the narrative
    version -- the same artifacts, read out at length with the reasoning attached. Both are
    generated from the same files, so they cannot disagree.
    """
    bundle_root = bundle_root or os.path.dirname(ledgers)
    g = lambda n: _load(ledgers, n) or {}                        # noqa: E731
    gb = lambda sub: _load(bundle_root, sub) or {}               # noqa: E731

    plan, corpus = g("plan.json"), g("corpus.json")
    fw, packing, masks = g("firewall.json"), g("packing.json"), g("masks.json")
    curric, cons, learn = g("mixture_compliance.json"), g("consumption_ledger.json"), \
        g("learning_ledger.json")
    opus, crash = g("opus.json"), g("crash_resume.json")
    rep, fork, aud = g("replay.json"), g("fork.json"), g("audit.json")
    adv = g("v6_shard_advisory.json")

    shards = gb("manifests/shard_index.json")
    tokz = gb("manifests/tokenizer.json")
    ckpt = gb("checkpoints/checkpoint_index.json")
    perf = gb("performance.json")
    summary = gb("run_summary.json")
    env = summary

    d = _Doc()
    d.h(1, "EVIDENCE")
    d.p("Generated by `run_demo.py` from the artifacts in `submission_artifacts/`. Every number below is "
        "read out of a JSON file produced by the run; nothing here is typed in by hand. "
        "Re-running the demo regenerates this document.")

    if summary:
        d.table(
            ["run", "wall clock", "steps", "loss", "parameters"],
            [[summary.get("run_id"), "{}s".format(summary.get("wall_clock_s")),
              summary.get("steps"),
              "{} -> {}".format(summary.get("initial_loss"), summary.get("final_loss")),
              (summary.get("model") or {}).get("parameters")]])

    # ---- headline checks ------------------------------------------------
    d.h(2, "Headline checks")
    checks: List[List[Any]] = []

    def add(name: str, ok: Optional[bool], detail: str, artifact: str) -> None:
        checks.append([_mark(ok), name, detail, "`{}`".format(artifact)])

    add("S5 plan reproduces", plan.get("plan_verified"),
        "{} stages, {} lanes, {} problems".format(
            len(plan.get("stages", [])), len(plan.get("lane_budget_shares", {})),
            len(plan.get("verification_problems", []))),
        "ledgers/plan.json")
    add("Tokenizer frozen and hashed", bool(tokz.get("tokenizer_hash")),
        "vocab {}, hash {}".format(tokz.get("vocab_size"),
                                   str(tokz.get("tokenizer_hash"))[:12]),
        "manifests/tokenizer.json")
    add("Evaluation firewall clean",
        aud.get("evaluation_leak", {}).get("clean"),
        "{} quarantined at build, {} eval docs consumed".format(
            len(fw.get("quarantined", [])),
            aud.get("evaluation_leak", {}).get(
                "documents_from_non_train_splits_consumed")),
        "ledgers/firewall.json + ledgers/audit.json")
    add("Shards immutable (built twice, same hash)",
        shards.get("immutability_all_identical"),
        "{} shards, registry {}".format(shards.get("shards"),
                                        str(shards.get("registry_hash"))[:12]),
        "manifests/shard_index.json")
    add("Shards survive a disk round-trip",
        shards.get("reload_verification", {}).get("all_ok"),
        "{} shards re-read and re-hashed".format(
            shards.get("reload_verification", {}).get("shards_checked")),
        "manifests/shard_index.json")
    add("Masks verified against their packed sequence", masks.get("all_clean"),
        "{} samples, block-diagonal attention proven to block".format(
            masks.get("samples_checked")),
        "ledgers/masks.json")
    init = cons.get("preflight", {}).get("initial_loss", {})
    add("Initial loss = ln(V)", init.get("ok"),
        "observed {} vs ln(V) {} (ratio {})".format(
            init.get("observed"), init.get("expected_ln_v"), init.get("ratio")),
        "ledgers/consumption_ledger.json")
    add("Embeddings trainable at every seam (S5 rule 1)",
        cons.get("preflight", {}).get("embeddings", {}).get("ok"),
        "tok_emb requires_grad and present in the optimizer",
        "ledgers/consumption_ledger.json")
    add("Checkpoint corruption detected",
        ckpt.get("torn_write_drill", {}).get("all_detected"),
        "{} corruption flavours, all caught".format(
            ckpt.get("torn_write_drill", {}).get("corruptions_tested")),
        "checkpoints/checkpoint_index.json")
    add("Crash/resume reproduces weights bitwise",
        crash.get("weights_bitwise_identical"),
        "checkpoint at {}, crash at {}".format(
            crash.get("checkpoint_at"), crash.get("crash_at")),
        "ledgers/crash_resume.json")
    add("Crash/resume repairs the ledger",
        crash.get("ledger_rows_identical"),
        "{} orphan rows discarded, {} rows match".format(
            crash.get("orphan_rows_repaired"), crash.get("ledger_rows_resumed")),
        "ledgers/crash_resume.json")
    add("Replay from the ledger reproduces batches",
        rep.get("all_match"),
        "{}/{} steps re-hash identically".format(
            rep.get("steps_matching"), rep.get("steps_replayed")),
        "ledgers/replay.json")
    checks.sort(key=lambda r: (r[0] != "FAIL",))
    d.table(["", "check", "detail", "artifact"], checks)

    failures = [c for c in checks if c[0] == "FAIL"]
    d.p("**{} of {} checks pass.**{}".format(
        len(checks) - len(failures), len(checks),
        "" if not failures else " Failing rows are retained above rather than removed."))

    # ---- 1. immutable shards --------------------------------------------
    d.h(2, "1. Immutable tokenized shards with manifests")
    d.p("Shards are content-addressed: the shard id embeds a hash of its own tokens, so a "
        "shard whose content changed cannot keep its name. Each is built twice from the "
        "same inputs and the two hashes compared.")
    d.table(["shards", "tokens", "trainable", "double-build identical", "reload ok"],
            [[shards.get("shards"), shards.get("total_tokens"), shards.get("trainable"),
              shards.get("immutability_all_identical"),
              shards.get("reload_verification", {}).get("all_ok")]])
    rows = (shards.get("rows") or [])[:6]
    if rows:
        d.table(["shard", "lane", "bands", "tokens", "docs", "trainable", "content hash"],
                [[r["shard_id"], r["lane"], r["bands"], r["tokens"], r["documents"],
                  r["trainable"], r["content_hash"]] for r in rows])
    untrainable = [r for r in (shards.get("rows") or []) if not r["trainable"]]
    if untrainable:
        d.p("Shards refused as untrainable, with the manifest field that refused them:")
        d.table(["shard", "reasons"],
                [[r["shard_id"], r["refusal_reasons"]] for r in untrainable[:6]])

    # ---- 2. tokenizer ----------------------------------------------------
    d.h(2, "2. Frozen tokenizer and content hashes")
    d.p("The tokenizer is fitted on the **train split only** -- a tokenizer that has seen "
        "held-out text has already leaked it. Its hash is written into every shard "
        "manifest, and the loader refuses any shard whose tokenizer hash differs from the "
        "one it holds.")
    d.table(["tokenizer id", "vocab", "hash", "fitted on"],
            [[tokz.get("tokenizer_id"), tokz.get("vocab_size"),
              str(tokz.get("tokenizer_hash"))[:16], tokz.get("trained_on")]])
    fert = tokz.get("fertility", {})
    frows = [[k, v.get("documents"), v.get("fertility_tokens_per_word"),
              v.get("chars_per_token")]
             for k, v in sorted(fert.items()) if not k.startswith("_")]
    if frows:
        d.p("**Tokenizer fertility** (tokens per whitespace word). The session's warning is "
            "that a vocabulary tuned for English turns a 1,000-word Telugu document into a "
            "13,000-token one -- which then has to be chopped, and the chop is a tokenizer "
            "failure wearing a packing costume:")
        d.table(["language/script", "docs", "tokens/word", "chars/token"], frows)
        agg = fert.get("_indic_aggregate")
        if agg:
            d.p("Indic aggregate: **{} tokens/word** against S5's target of {}. {}".format(
                agg.get("fertility_tokens_per_word"), agg.get("s5_target"),
                agg.get("note")))

    # ---- 3. packing ------------------------------------------------------
    d.h(2, "3. Packing policies that differ by data type")
    d.p("Every policy is run against one shard per lane at seq_len {}, so the cost of the "
        "policy each lane actually uses is a measurement rather than an assertion."
        .format((packing.get("windows") or {}).get("base")))
    for lane, comp in sorted((packing.get("policy_bakeoff") or {}).items()):
        prows = []
        for pol, st in sorted((comp.get("policies") or {}).items()):
            prows.append([pol, st.get("sequences"), st.get("packing_efficiency"),
                          st.get("padding_fraction"), st.get("documents_truncated"),
                          st.get("deferred_documents"),
                          "<- lane policy" if pol == comp.get("lane_policy") else ""])
        if prows:
            d.p("**{}** (shard `{}`, {} documents; the lane's own policy is `{}`)".format(
                lane, comp.get("shard_id"), comp.get("documents"),
                comp.get("lane_policy")))
            d.table(["policy", "seqs", "efficiency", "pad fraction", "truncated",
                     "deferred", ""], prows)

    # ---- 4. masks --------------------------------------------------------
    d.h(2, "4. Loss mask, attention mask, position ids")
    d.p(masks.get("what_this_is", ""))
    mrows = [[m["lane"], m["attention_policy"], m["position_policy"], m["real_tokens"],
              m["supervised_tokens"], m["supervision_yield"],
              "clean" if not m["problems"] else m["problems"]]
             for m in (masks.get("rows") or [])[:8]]
    if mrows:
        d.table(["lane", "attention", "positions", "real", "supervised", "yield", "verify"],
                mrows)

    # ---- 5. curriculum ---------------------------------------------------
    d.h(2, "5. Curriculum stages, lane weights, protected flows")
    d.table(["steps", "seam steps", "schedule hash", "stage step counts"],
            [[(curric.get("schedule") or {}).get("steps"), curric.get("seam_steps"),
              str(curric.get("schedule_hash", ""))[:12],
              (curric.get("schedule") or {}).get("stage_step_counts")]])
    realized = (curric.get("schedule") or {}).get("integrated_realized_weights") or {}
    targets = plan.get("integrated_lane_shares_main_run") or {}
    if realized:
        d.p("Realized lane shares against the S5 targets. The gaps are the plan's own "
            "constraints binding, not drift:")
        d.table(["lane", "target", "realized", "delta"],
                [[ln, targets.get(ln), realized.get(ln),
                  round((realized.get(ln) or 0) - (targets.get(ln) or 0), 5)]
                 for ln in sorted(realized)])
    if (curric.get("schedule") or {}).get("lane_epochs_demo"):
        d.p("Epochs consumed against the {}-epoch repetition ceiling "
            "(arXiv:2305.16264), demo run beside the plan's own figure:".format(
                curric.get("epoch_ceiling")))
        d.table(["lane", "demo epochs", "plan epochs", "supply tokens", "delivered"],
                [[k, v, ((curric.get("schedule") or {}).get("lane_epochs_plan") or {}).get(k),
                  ((curric.get("schedule") or {}).get("lane_supply_tokens") or {}).get(k),
                  ((curric.get("schedule") or {}).get("lane_delivered_tokens") or {}).get(k)]
                 for k, v in sorted((curric.get("schedule") or {})["lane_epochs_demo"].items())])
        d.p((curric.get("schedule") or {}).get("note", ""))
    if (curric.get("schedule") or {}).get("shortfalls"):
        d.p("Lanes that could not be served in full, and why:")
        d.table(["lane", "detail"],
                [[k, _fmt(v)] for k, v in sorted((curric.get("schedule") or {})["shortfalls"].items())])

    # ---- 6. firewall -----------------------------------------------------
    d.h(2, "6. Evaluation and validation firewall (two-sided)")
    d.p("Build side: documents are admitted, deduplicated, and scanned for n-gram overlap "
        "with the evaluation set. Consumption side: the audit re-asks the question from "
        "the *consumed* documents, which is the check that would catch a leak the build "
        "side missed.")
    d.table(["admitted", "refused", "exact dup", "near dup", "quarantined", "eval docs"],
            [[fw.get("admitted"), len(fw.get("refused", [])),
              len(fw.get("exact_duplicates", [])), len(fw.get("near_duplicates", [])),
              len(fw.get("quarantined", [])), fw.get("eval_documents")]])
    if fw.get("refused"):
        d.p("Refusals, with the reason each was refused for:")
        d.table(["doc", "reasons"],
                [[r["doc_id"], r["reasons"]] for r in fw["refused"][:6]])
    if fw.get("quarantined"):
        d.p("Contamination quarantine -- documents sharing an n-gram with an evaluation "
            "document:")
        d.table(["doc", "matched eval doc"],
                [[q["doc_id"], q["matched_eval_doc"]] for q in fw["quarantined"][:6]])
    leak = aud.get("evaluation_leak", {})
    d.p("Consumption-side check: **{}** documents from non-train splits were consumed "
        "across {} steps.".format(
            leak.get("documents_from_non_train_splits_consumed"), aud.get("steps_audited")))

    # ---- 7. opus ---------------------------------------------------------
    d.h(2, "7. OPUS acceptance, rejection, deferral, protected override")
    d.table(["target accept rate", "probe tokens", "rounds", "proxy top-k"],
            [[opus.get("accept_rate_target"), opus.get("probe_tokens"),
              len(opus.get("rounds", [])), opus.get("proxy_top_k")]])
    orows = [[r["step"], r["stage"], r["candidates"], r["accepted"], r["rejected"],
              r["deferred"], r["protected_overrides"], r["threshold"],
              r["merit_alignment_mean"]]
             for r in opus.get("rounds", [])]
    if orows:
        d.table(["step", "stage", "cands", "acc", "rej", "defer", "protected",
                 "threshold", "merit align"], orows)
    reasons: Dict[str, int] = {}
    for r in opus.get("rounds", []):
        for k, v in (r.get("reasons") or {}).items():
            reasons[k] = reasons.get(k, 0) + v
    if reasons:
        d.p("Decision reasons across all rounds. Every rejection is retained in "
            "`logs/opus_trail.jsonl`: what was thrown away is as informative as what was "
            "kept, and it is the only record of it.")
        d.table(["reason", "count"], sorted(reasons.items()))
    drift = opus.get("drift", {})
    d.p("**Selection drift.** {} Measured over {}. First round {}, last round {}, "
        "delta {} -> `{}`. Confidence: {}".format(
            drift.get("verdict", "").split(":")[-1].strip() or "n/a",
            drift.get("measured_over"), drift.get("first_round_merit_mean"),
            drift.get("last_round_merit_mean"), drift.get("delta"),
            drift.get("verdict", "").split(":")[0], drift.get("confidence")))

    # ---- 8. ledgers ------------------------------------------------------
    d.h(2, "8. Consumption ledger and learning ledger")
    d.p("**Consumption ledger** -- what went out. " + cons.get("what_this_is", ""))
    d.table(["steps", "tokens", "supervised", "yield", "shards", "documents", "hash"],
            [[cons.get("steps"), cons.get("total_tokens"),
              cons.get("total_supervised_tokens"), cons.get("supervision_yield"),
              cons.get("shards_touched"), cons.get("documents_touched"),
              str(cons.get("ledger_hash", ""))[:12]]])
    if cons.get("lane_shares"):
        d.table(["lane", "tokens", "share"],
                [[ln, cons["lane_tokens"][ln], cons["lane_shares"][ln]]
                 for ln in sorted(cons["lane_shares"])])

    d.p("**Learning ledger** -- what came back. " + learn.get("what_this_is", ""))
    curve = learn.get("loss_curve") or []
    if curve:
        d.table(["step", "stage", "loss", "perplexity", "grad norm", "lr"],
                [[c["step"], c["stage"], c["mean_loss"], c["perplexity"],
                  c["grad_norm"], c["lr"]]
                 for c in (curve[:3] + (["..."] if len(curve) > 6 else []) + curve[-3:])
                 if isinstance(c, dict)])
        d.p("Loss {} -> {} (perplexity {} -> {}) over {} steps.".format(
            curve[0]["mean_loss"], curve[-1]["mean_loss"],
            curve[0]["perplexity"], curve[-1]["perplexity"], len(curve)))
    if learn.get("by_lane"):
        d.p("Loss attributed by lane:")
        d.table(["lane", "supervised tokens", "mean loss", "perplexity"],
                [[k, v["tokens"], v["mean_loss"], v["perplexity"]]
                 for k, v in sorted(learn["by_lane"].items())])
    if learn.get("by_role"):
        d.p("Loss attributed by **role**. This is the number a lane-level average cannot "
            "give you: on agentic data it separates learning to act from learning to "
            "narrate around the action.")
        d.table(["role", "tokens", "mean loss", "perplexity"],
                [[k, v["tokens"], v["mean_loss"], v["perplexity"]]
                 for k, v in sorted(learn["by_role"].items())])
    if learn.get("by_band"):
        d.table(["difficulty band", "tokens", "mean loss", "perplexity"],
                [[k, v["tokens"], v["mean_loss"], v["perplexity"]]
                 for k, v in sorted(learn["by_band"].items())])
        if learn.get("by_band_caveat"):
            d.p("_{}_".format(learn["by_band_caveat"]))
    if learn.get("by_lane_by_stage"):
        d.p("Loss by lane **within each stage** -- the band table's confound removed, since "
            "a stage is a fixed slice of model age:")
        stages = sorted({st for v in learn["by_lane_by_stage"].values() for st in v})
        d.table(["lane"] + stages,
                [[lane] + [(learn["by_lane_by_stage"][lane].get(st) or {}).get("perplexity")
                           for st in stages]
                 for lane in sorted(learn["by_lane_by_stage"])])
    eos = learn.get("eos_prediction", {})
    if eos:
        d.p("**EOS perplexity: {}** over {} EOS tokens. {}".format(
            eos.get("perplexity"), eos.get("tokens"), eos.get("note")))
    if learn.get("hardest_tokens"):
        d.p("The hardest individual tokens seen, decoded -- the exemplars that make a "
            "high-loss shard actionable rather than merely flagged:")
        d.table(["step", "lane", "token", "role", "loss"],
                [[t["step"], t["lane"], repr(t["token"]), t["role"], t["loss"]]
                 for t in learn["hardest_tokens"][:8]])

    # ---- 9. checkpoint / crash / replay ----------------------------------
    d.h(2, "9. Checkpoint, crash, resume, replay")
    d.p(ckpt.get("what_this_is", ""))
    d.table(["checkpoints", "all verify", "corruption flavours tested", "all detected"],
            [[ckpt.get("checkpoints"),
              all(v.get("ok") for v in ckpt.get("verification", [])) or None,
              ckpt.get("torn_write_drill", {}).get("corruptions_tested"),
              ckpt.get("torn_write_drill", {}).get("all_detected")]])
    tw = ckpt.get("torn_write_drill", {})
    if tw.get("results"):
        d.table(["induced corruption", "detected", "how"],
                [[r["flavour"], r["detected"], r["problems"]] for r in tw["results"]])
        d.p(tw.get("note", ""))

    d.p("**Crash and resume.** " + (crash.get("what_this_is") or ""))
    d.table(["checkpoint at", "crash at", "ledger rows on disk", "orphan rows repaired",
             "weights identical", "ledger identical", "totals match"],
            [[crash.get("checkpoint_at"), crash.get("crash_at"),
              crash.get("ledger_rows_on_disk_at_crash"),
              crash.get("orphan_rows_repaired"),
              crash.get("weights_bitwise_identical"),
              crash.get("ledger_rows_identical"),
              crash.get("consumption_totals_match")]])
    d.p("The orphan rows are the point. The ledger was appended to for every step up to the "
        "crash; the weights only got as far as the checkpoint. A resume that keeps those "
        "rows claims the model consumed tokens it has never seen -- in the one artifact "
        "whose entire purpose is to be believed.")

    d.p("**Replay.** " + (rep.get("what_this_is") or ""))
    d.table(["steps replayed", "matching", "all match"],
            [[rep.get("steps_replayed"), rep.get("steps_matching"), rep.get("all_match")]])
    we = rep.get("worked_example") or {}
    if we.get("documents"):
        d.p("Worked example -- step {} of the run, reconstructed from the ledger alone:"
            .format(we.get("step")))
        d.table(["doc", "lane", "band", "packing", "attention", "positions"],
                [[x["doc_id"], x["lane"], x["band"], x["packing_policy"],
                  x["attention_policy"], x["position_policy"]]
                 for x in we["documents"][:6]])
        prev = next((x.get("text_preview") for x in we["documents"] if x.get("text_preview")),
                    None)
        if prev:
            d.code(prev)

    # ---- 10. fork --------------------------------------------------------
    d.h(2, "10. Fork: the controlled counterfactual")
    d.p(fork.get("what_this_is", ""))
    for name, b in sorted((fork.get("branches") or {}).items()):
        d.p("**{}** -- override `{}`, mean loss {}, binding drift `{}`".format(
            name, b.get("lane_weight_override"), b.get("mean_loss"),
            b.get("binding_drift") or "none"))
    comp = fork.get("comparison") or {}
    if comp.get("per_lane_token_delta"):
        d.table(["lane", "token delta", "loss delta"],
                [[ln, comp["per_lane_token_delta"].get(ln),
                  comp.get("per_lane_loss_delta", {}).get(ln)]
                 for ln in sorted(comp["per_lane_token_delta"])])

    # ---- 11. audit -------------------------------------------------------
    d.h(2, "11. Audit")
    d.p(aud.get("what_this_is", ""))
    if aud.get("provenance_chains"):
        d.p("Provenance, end to end -- a consumed token traced back to a licence:")
        for c in aud["provenance_chains"][:2]:
            d.code(json.dumps(c, indent=2))
    if aud.get("most_repeated_documents"):
        d.table(["document", "exposures"],
                [[r["doc_id"], r["exposures"]]
                 for r in aud["most_repeated_documents"][:6]])

    # ---- 12. advisory ----------------------------------------------------
    d.h(2, "12. The v6 shard advisory")
    d.p(adv.get("what_this_is", ""))
