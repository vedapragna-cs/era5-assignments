def evaluate(root: str) -> Dict[str, Any]:
    """Run every predicate against the artifacts on disk."""
    rows: List[Dict[str, Any]] = []
    cache: Dict[str, Any] = {}

    for req in REQUIREMENTS:
        path = os.path.join(root, req.artifact)
        row: Dict[str, Any] = {
            "requirement": req.name,
            "key": req.key,
            "evidence_label": req.evidence_label,
            "artifact": req.artifact,
            "pointer": req.pointer,
            "check_expression": req.check_expression,
        }

        if req.artifact not in cache:
            if not os.path.exists(path):
                cache[req.artifact] = None
            else:
                with open(path) as fh:
                    cache[req.artifact] = json.load(fh)
        doc = cache[req.artifact]

        if doc is None:
            row.update({"result": "FAIL", "error": "artifact missing: {}".format(path)})
            rows.append(row)
            continue

        found, value = _dig(doc, req.pointer)
        if not found:
            # An unresolvable pointer is an error, not a pass. Silently treating a missing
            # value as False would report a broken bundle as a failing subsystem, which
            # sends the reader to the wrong place.
            row.update({"result": "FAIL",
                        "error": "evidence pointer {} does not resolve in {}".format(
                            req.pointer, req.artifact)})
            rows.append(row)
            continue

        try:
            passed = bool(req.check(value))
        except Exception as exc:  # a predicate that raises is a failure, not a crash
            row.update({"result": "FAIL",
                        "error": "{}: {}".format(type(exc).__name__, exc)})
            rows.append(row)
            continue

        details = {}
        for p in req.detail_pointers:
            ok, v = _dig(doc, p)
            if ok:
                details[p.strip("/")] = v

        row.update({
            "result": "PASS" if passed else "FAIL",
            "observed_value": value,
            "details": details,
        })
        rows.append(row)

    passed = sum(1 for r in rows if r["result"] == "PASS")
    return {
        "requirements": rows,
        "total": len(rows),
        "passed": passed,
        "failed": len(rows) - passed,
        "all_passed": passed == len(rows),
    }


def build_bundle(root: str, *, run_meta: Dict[str, Any],
                 log_summary: Dict[str, Any]) -> Dict[str, Any]:
    """Assemble evidence.json."""
    ev = evaluate(root)

    inventory = []
    for dirpath, _dirs, files in os.walk(root):
        for f in sorted(files):
            if f in ("evidence.json", "evidence.md"):
                continue
            full = os.path.join(dirpath, f)
            inventory.append({
                "path": os.path.relpath(full, root),
                "bytes": os.path.getsize(full),
            })

    return {
        "schema": "era5-s6-evidence-v1",
        "generated_by": "run_demo.py -> ledger/evidence.py",
        "how_to_verify": (
            "Every row's `result` is produced by evaluating `check_expression` against "
            "`pointer` inside `artifact`. Nothing is hardcoded: re-running run_demo.py "
            "regenerates the artifacts and re-evaluates every predicate against them. To "
            "check a row by hand, open the named artifact and resolve the pointer."),
        "run": run_meta,
        "execution_log": log_summary,
        "summary": {
            "requirements_total": ev["total"],
            "requirements_passed": ev["passed"],
            "requirements_failed": ev["failed"],
            "all_passed": ev["all_passed"],
            "log_events": log_summary.get("events"),
            "log_pass": log_summary.get("pass"),
            "log_fail": log_summary.get("fail"),
            "required_events_missing": log_summary.get("required_events_missing"),
        },
        "requirements": ev["requirements"],
        "artifact_inventory": inventory,
    }


def write_evidence_md(bundle: Dict[str, Any], path: str) -> str:
    """evidence.md -- the handout's REQUIREMENT / RESULT / EVIDENCE table, plus context."""
    L: List[str] = []
    s = bundle["summary"]
    run = bundle.get("run", {})

    L.append("# Evidence")
    L.append("")
    L.append("Generated by `run_demo.py`. Every row below was produced by evaluating a "
             "predicate against an artifact this run wrote; none of it is hardcoded.")
    L.append("")
    L.append("| | |")
    L.append("|---|---|")
    L.append("| Run | `{}` |".format(run.get("run_id")))
    L.append("| Command | `{}` |".format(run.get("command")))
    L.append("| Wall clock | {}s |".format(run.get("wall_clock_s")))
    L.append("| Requirements | **{}/{} passed** |".format(
        s["requirements_passed"], s["requirements_total"]))
    L.append("| Log events | {} ({} PASS, {} FAIL) |".format(
        s.get("log_events"), s.get("log_pass"), s.get("log_fail")))
    L.append("")

    L.append("## Requirements")
    L.append("")
    L.append("| REQUIREMENT | RESULT | EVIDENCE |")
    L.append("|---|---|---|")
    for r in bundle["requirements"]:
        L.append("| {} | **{}** | {} — `{}`{} |".format(
            r["requirement"], r["result"], r["evidence_label"], r["artifact"],
            "" if r["result"] == "PASS" else " ({})".format(r.get("error", "check failed"))))
    L.append("")

    if s["requirements_failed"]:
        L.append("> **{} requirement(s) failed.** Failing rows are retained above rather "
                 "than removed.".format(s["requirements_failed"]))
        L.append("")

    L.append("## What each row asserts")
    L.append("")
    L.append("The `check` column is the predicate that was evaluated. The `observed` column "
             "is the value it read out of the artifact at the given pointer.")
    L.append("")
    for r in bundle["requirements"]:
        L.append("### {} — {}".format(r["requirement"], r["result"]))
        L.append("")
        L.append("- **Check**: {}".format(r["check_expression"]))
        L.append("- **Evidence**: `{}` at `{}`".format(r["artifact"], r["pointer"]))
        L.append("- **Observed**: `{}`".format(json.dumps(r.get("observed_value"))))
        if r.get("details"):
            for k, v in r["details"].items():
                L.append("  - `{}` = `{}`".format(k, json.dumps(v)[:200]))
        if r.get("error"):
            L.append("- **Error**: {}".format(r["error"]))
        L.append("")

    log = bundle.get("execution_log", {})
    L.append("## Execution log")
    L.append("")
    L.append("`run.log` records the full event sequence. Required events present: "
             "**{}/{}**.".format(log.get("required_events_present"),
                                 log.get("required_events_total")))
    if log.get("required_events_missing"):
        L.append("")
        L.append("Missing: {}".format(", ".join(log["required_events_missing"])))
    L.append("")

    L.append("## Artifact inventory")
    L.append("")
    L.append("| file | bytes |")
    L.append("|---|---|")
    for a in bundle["artifact_inventory"]:
        L.append("| `{}` | {} |".format(a["path"], a["bytes"]))
    L.append("")

    text = "\n".join(L)
    with open(path, "w") as fh:
        fh.write(text)
    return path
