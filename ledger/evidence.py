"""The evidence bundle: evidence.json and evidence.md.

The handout's rule is that the bundle must be *generated by the implementation* and that
hardcoded evidence will not be accepted. That constraint shapes this module more than
anything else in the repository, so it is worth being explicit about how it is honoured.

Every requirement below is a `Requirement` whose `result` is computed by a **predicate over
the artifacts on disk**. The predicate receives the loaded JSON and returns a bool. There is
no code path that can write PASS without a predicate having returned True against a file the
run produced. The predicate's source text is itself recorded in `evidence.json` under
`check_expression`, so a reviewer can see exactly what was asserted without reading this
file -- and can re-evaluate it themselves against the same artifacts.

The `evidence_path` on each requirement is a JSON pointer into the bundle. It is verified to
resolve before the row is emitted: a requirement whose evidence cannot be located is
reported as an error rather than quietly passing on the strength of its predicate.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, List, Optional, Tuple


@dataclass
class Requirement:
    key: str
    name: str                  # the handout's row label
    artifact: str              # file under submission_artifacts/
    pointer: str               # slash-path into that file
    check: Callable[[Any], bool]
    check_expression: str      # human-readable form of `check`, recorded in the bundle
    evidence_label: str        # the handout's EVIDENCE column
    detail_pointers: Tuple[str, ...] = ()


def _dig(obj: Any, pointer: str) -> Tuple[bool, Any]:
    """Resolve a slash-path. Returns (found, value)."""
    cur = obj
    if pointer in ("", "/"):
        return True, cur
    for part in pointer.strip("/").split("/"):
        if isinstance(cur, list):
            try:
                cur = cur[int(part)]
            except (ValueError, IndexError):
                return False, None
        elif isinstance(cur, dict):
            if part not in cur:
                return False, None
            cur = cur[part]
        else:
            return False, None
    return True, cur


